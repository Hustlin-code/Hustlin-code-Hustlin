/* Adds (or refreshes) the calculator block in sitemap.xml.
   Idempotent: re-running replaces the block rather than appending. */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CALCS } from './calc-content.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const F = join(ROOT, 'sitemap.xml');
/* Was a hardcoded '2026-08-08'. A <lastmod> that never moves is worse than no
   <lastmod> at all - it tells a crawler the page has not changed since the day
   someone last remembered to edit this line. */
const TODAY = new Date().toISOString().slice(0, 10);

const START = '  <!-- CALC:START -->';
const END = '  <!-- CALC:END -->';

const urls = CALCS.map(c => `  <url>
    <loc>https://hustlin.org/${c.slug}.html</loc>
    <lastmod>${TODAY}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>`).join('\n\n');

const block = `${START}
  <!-- Calculators. Generated by tools/build-calculators.mjs; this block is
       written by tools/update-sitemap-calcs.mjs. Do not hand-edit.

       WHY THESE EXIST SEPARATELY FROM calculate-your-hustle.html.
       Every calculator used to live on that one URL behind a #anchor. An
       anchor is not a document - Google indexes the page, never the
       fragment - so a single URL was competing for "budget calculator",
       "mortgage calculator", "paycheck calculator" and eleven other
       distinct intents at once, and could rank properly for none of them.
       Each page below now carries its own title, meta description,
       canonical, the formula explained, a worked example and its own
       FAQPage schema.

       The hub page is not a duplicate of these and keeps its own
       canonical: it is the "all of them at once" entry point, and it
       links out to each of these. Every calculator page links back to the
       hub and sideways to the other thirteen through the sidebar rail, so
       the internal link graph is complete in both directions.

       Adding a calculator: add it to tools/calc-content.mjs, run the
       builder, then re-run this script in the same change. -->

${urls}
${END}`;

let s = readFileSync(F, 'utf8');
if (s.includes(START)) {
  s = s.replace(new RegExp(START.trim() + '[\\s\\S]*?' + END.trim()), block.trim());
} else {
  const anchor = '  <!-- ─── Blog ─────────────────────────────────────────── -->';
  if (!s.includes(anchor)) throw new Error('Blog anchor comment not found in sitemap.xml');
  s = s.replace(anchor, block + '\n\n' + anchor);
}
writeFileSync(F, s, 'utf8');
console.log(`sitemap: ${CALCS.length} calculator URLs written`);
