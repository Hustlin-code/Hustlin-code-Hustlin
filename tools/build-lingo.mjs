/* ===================================================================
   build-lingo.mjs
   -------------------------------------------------------------------
   Generates the Learn the Lingo glossary pages from lingo-content.mjs
   and rewrites the A-Z index on learn-the-lingo.html to match.

   RUN:  node tools/build-lingo.mjs
         node tools/build-lingo.mjs --check   (writes nothing, exits 1
                                               if a page is out of date)

   WHY A GENERATOR
   Same reason build-calculators.mjs exists. Every term page carries the
   same head, the same JSON-LD @graph, the same nav, the same rail and
   the same disclaimer. Hand-maintaining that across nine files is how
   one page ends up with a canonical pointing at the wrong URL and a
   FAQPage block that disagrees with the visible FAQ.

   WHAT IT DOES NOT DO
   Footers - tools/stamp-footers.mjs owns those and must run after this.
   The template emits FOOTER:START/END empty and the stamper fills them.
   The nav block is read from nav.template.html so it comes out already
   stamped and stamp-nav.mjs --check passes with no extra step; if those
   two ever drift, every glossary page fails the nav gate at once.

   ORDER: build-lingo -> stamp-footers -> update sitemap if a term is new.
   =================================================================== */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TERMS, REVIEWED } from './lingo-content.mjs';
import { navFor, GROUPS, termsInGroup } from './nav-template.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://hustlin.org';
const DIR = 'learn-the-lingo';
const CHECK = process.argv.includes('--check');
/* --fresh ignores the existing file entirely: no footer carry-forward, no
   up-to-date skip. Use it after a template change that left a page malformed,
   then run stamp-footers.mjs. */
const FRESH = process.argv.includes('--fresh');
const R = (p) => readFileSync(join(ROOT, p), 'utf8');

/* stamp-footers.mjs finds its block by an EXACT marker string that carries a
   "generated by" note inside the comment. Emitting the bare <!-- FOOTER:START -->
   pair instead meant the stamper could not find a block to fill, appended its own
   before </body>, and the next rebuild's carry-forward duplicated it — three
   markers and two footers on every page. The tripwire below fails the build
   loudly if that string ever changes in stamp-footers.mjs, rather than letting
   it drift and reproduce the same mess. */
const FOOTER_START = '<!-- FOOTER:START — generated by tools/stamp-footers.mjs from footer.template.html. DO NOT EDIT BY HAND. -->';
const FOOTER_END = '<!-- FOOTER:END -->';
if (!R('tools/stamp-footers.mjs').includes(FOOTER_START)) {
  throw new Error('FOOTER_START no longer matches the marker in tools/stamp-footers.mjs — update build-lingo.mjs');
}

/* Depth 1: every glossary page sits in learn-the-lingo/. navFor() applies the
   same transform stamp-nav.mjs does, from the same module, so these pages come
   out already stamped and the nav gate passes with no extra step. */
const NAV_BLOCK = '<!-- NAV:START -->\n' + navFor(1) + '\n<!-- NAV:END -->';

const BY_SLUG = Object.fromEntries(TERMS.map((t) => [t.slug, t]));
const jstr = (s) => JSON.stringify(String(s));

/* The visible FAQ and the FAQPage block are written from ONE array, so they
   cannot disagree. Google treats a mismatch as a structured-data violation
   and it is the single easiest way for a hand-maintained page to go wrong. */
const faqJsonLd = (t) => t.faq.map((f) => `        {
          "@type": "Question",
          "name": ${jstr(f.q)},
          "acceptedAnswer": { "@type": "Answer", "text": ${jstr(f.a)} }
        }`).join(',\n');

const relCard = (r) => {
  const target = BY_SLUG[r.slug];
  if (!target) throw new Error(`related term "${r.slug}" is not in TERMS`);
  return `      <a href="${r.slug}.html"><b>${r.label}</b><span>${r.blurb}</span></a>`;
};

/* t.tool.lbl is optional and defaults to "Run the numbers".
   The trading and markets terms added 2026-08-12 point their rail card at a live
   Markets pillar rather than a calculator - the site has no technical-analysis
   calculator - and "Run the numbers" over a link to a chart is the wrong promise.
   Omitting lbl reproduces the previous output byte for byte, which is why the
   twenty-eight existing terms did not need touching. */
