/* ---------- the hub's A-Z index ----------------------------------- */

const LETTERS = ['#', ...'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')];
// A term whose name starts with a digit files under '#'. The anchor id cannot be
// '#' itself (href="##" is not a link), so the '#' bucket anchors to id="num".
const anchorId = (L) => (L === '#' ? 'num' : L);

function indexBlocks() {
  const byLetter = new Map();
  for (const t of TERMS) {
    const label = t.shortName && t.shortName !== t.term ? `${t.shortName} (${t.term})` : t.term;
    if (!byLetter.has(t.letter)) byLetter.set(t.letter, []);
    byLetter.get(t.letter).push({ label, blurb: t.indexBlurb, slug: t.slug });
  }
  for (const rows of byLetter.values()) rows.sort((a, b) => a.label.localeCompare(b.label));

  const jump = LETTERS.map((L) =>
    byLetter.has(L) ? `    <a href="#${anchorId(L)}">${L}</a>` : `    <a class="is-empty" href="#${anchorId(L)}">${L}</a>`
  ).join('\n');

  const groups = LETTERS.filter((L) => byLetter.has(L)).map((L) => {
    const rows = byLetter.get(L)
      .map((r) => `      <a href="${DIR}/${r.slug}.html"><b>${r.label}</b><span>${r.blurb}</span></a>`)
      .join('\n');
    return `  <section class="gls-idx-group">\n    <h2 class="gls-idx-letter" id="${anchorId(L)}">${L}</h2>\n    <div class="gls-idx-rows">\n${rows}\n    </div>\n  </section>`;
  }).join('\n\n');

  return { jump, groups };
}

/* The hub's "Browse by topic" sections.
   -----------------------------------------------------------------------
   Generated from the SAME GROUPS array the nav panel is built from, so a
   nav tile can never point at an anchor that does not exist. The anchor
   ids are id="g-<key>", matching the hrefs in nav-template.mjs.

   These sections deliberately repeat terms that also appear in the A-Z
   index below them. Two ways in is the point: the nav sends topic
   browsers here, and someone who knows the word uses the letters. */
function topicBlocks() {
  return GROUPS.map((g) => {
    const rows = termsInGroup(g.key)
      .map((t) => {
        const label = t.shortName && t.shortName !== t.term ? `${t.shortName} (${t.term})` : t.term;
        return `      <a href="${DIR}/${t.slug}.html"><b>${label}</b><span>${t.indexBlurb}</span></a>`;
      })
      .join('\n');
    const n = termsInGroup(g.key).length;
    return `  <section class="gls-top-group" id="g-${g.key}">\n    <h3 class="gls-top-h">${g.label}<span>${n} terms</span></h3>\n    <div class="gls-idx-rows">\n${rows}\n    </div>\n  </section>`;
  }).join('\n\n');
}

function hub(html) {
  for (const mk of ['<!-- LINGO-INDEX:START', '<!-- LINGO-INDEX:END', '<!-- LINGO-TOPICS:START', '<!-- LINGO-TOPICS:END']) {
    if (!html.includes(mk)) throw new Error(`learn-the-lingo.html is missing ${mk} — the hub block markers are the only thing telling the builder where to write.`);
  }
  const { jump, groups } = indexBlocks();
  let out = html.replace(
    /(<nav class="gls-idx-jump" aria-label="Jump to letter">\n)[\s\S]*?(\n  <\/nav>)/,
    (m, a, b) => a + jump + b
  );
  /* Marker-anchored, not position-anchored. The old regex ran from the first
     .gls-idx-group to the first blank-line </div>, which only worked while the
     A-Z index was the LAST thing in .gls-idx. The index was moved above "Browse
     by topic" on 2026-08-15 and that regex would have swallowed the topic
     sections whole. Markers make the block order-independent, the same contract
     LINGO-TOPICS already had. */
  out = out.replace(
    /(  <!-- LINGO-INDEX:START[^>]*-->\n)[\s\S]*?(  <!-- LINGO-INDEX:END -->)/,
    (m, a, b) => a + groups + '\n' + b
  );
  /* Callback, not a string: the generated markup is full of dollar amounts
     and "$&" or "$1" in a replacement string would be read as a backreference. */
  out = out.replace(
    /(<!-- LINGO-TOPICS:START[^>]*-->\n)[\s\S]*?(  <!-- LINGO-TOPICS:END -->)/,
    (m, a, b) => a + topicBlocks() + '\n' + b
  );
  return out;
}

/* ---------- run --------------------------------------------------- */

let wrote = 0;
const stale = [];

for (const t of TERMS) {
  if (t.generated === false) continue;
  const rel = `${DIR}/${t.slug}.html`;
  const next = page(t);
  const prev = existsSync(join(ROOT, rel)) ? R(rel) : null;

  /* Compare with the cache-bust token normalised. The deploy rewrites ?v= at
     step 6, so a page that is byte-identical apart from its stamp is current,
     not drifted. Skipping this is how a --check gate learns to cry wolf after
     every single deploy. */
  const norm = (s) => (s === null ? null : s.replace(/\.(js|css)\?v=[^"']*/g, '.$1?v=X')
                                            .replace(/<!-- FOOTER:START[\s\S]*?FOOTER:END -->/, 'F'));
  if (!FRESH && norm(prev) === norm(next)) continue;

  if (CHECK) { stale.push(rel); continue; }

  /* Carry an existing stamped footer forward, exactly as build-calculators
     does, so a rebuild does not un-stamp every page and fail gate 2. */
  /* stamp-footers.mjs writes its own START marker with a "generated by" note in
     it, NOT the bare one this template emits. Matching only the bare marker made
     --check report all nine pages stale after every footer stamp — a gate that
     always fails is a gate you learn to ignore. */
  const keep = !FRESH && prev && /<!-- FOOTER:START[\s\S]*?FOOTER:END -->/.exec(prev);
  const body = keep ? next.replace(`${FOOTER_START}\n${FOOTER_END}`, keep[0]) : next;
  writeFileSync(join(ROOT, rel), body, 'utf8');
  wrote++;
  console.log(`  ${rel}`);
}

const hubPath = 'learn-the-lingo.html';
const hubPrev = R(hubPath);
const hubNext = hub(hubPrev);
if (hubPrev !== hubNext) {
  if (CHECK) stale.push(hubPath);
  else { writeFileSync(join(ROOT, hubPath), hubNext, 'utf8'); wrote++; console.log(`  ${hubPath} (A-Z index)`); }
}

const total = TERMS.filter((t) => t.generated !== false).length;
console.log(`\n${CHECK ? 'checked' : 'built'} ${total} generated term page(s) + the hub index` +
            (CHECK ? '' : `, ${wrote} file(s) written`));

if (CHECK && stale.length) {
  console.log('\nThese are out of date with lingo-content.mjs:');
  for (const s of stale) console.log(`  ${s}`);
  console.log('\nFix with:  node tools/build-lingo.mjs');
  process.exitCode = 1;
}
